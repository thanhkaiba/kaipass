/** Keeps the drawing, drops sizes, classes and comments; the app sizes icons with CSS. */
function clean(svg) {
  const body = svg.replace(/<!--[\s\S]*?-->/g, '');
  // Only the outer <svg> loses its size and class: shapes inside (a <rect width=...>) need theirs.
  return body
    .replace(/<svg\b[^>]*>/, (tag) => tag.replace(/\s(width|height|class)="[^"]*"/g, ''))
    .replace(/<svg\b/, '<svg aria-hidden="true" focusable="false"')
    .replace(/\s+/g, ' ')
    .replace(/> </g, '><')
    .trim();
}

const packs = {
  lucide: (i) => join(nm, 'lucide-static/icons', `${MAP[i][0]}.svg`),
  phosphor: (i) => join(nm, '@phosphor-icons/core/assets/regular', `${MAP[i][1]}.svg`),
  'phosphor-duotone': (i) => join(nm, '@phosphor-icons/core/assets/duotone', `${MAP[i][1]}-duotone.svg`),
  'phosphor-fill': (i) => join(nm, '@phosphor-icons/core/assets/fill', `${MAP[i][1]}-fill.svg`),
  pixel: (i) => join(nm, 'pixelarticons/svg', `${MAP[i][2]}.svg`),
};

for (const [pack, file] of Object.entries(packs)) {
  const icons = {};
  for (const name of Object.keys(MAP)) icons[name] = clean(readFileSync(file(name), 'utf8'));
  writeFileSync(
    join(__dirname, '..', 'src/icons', `${pack}.ts`),
    `// Generated by scripts/gen-icons.cjs. Do not edit by hand.\nconst icons: Record<string, string> = ${JSON.stringify(icons, null, 2)};\nexport default icons;\n`,
  );
  console.log(pack, Object.keys(icons).length, 'icons');
}
